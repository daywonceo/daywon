// Helper function to get user by ID
export const getUserById = (userId: string) => {
  return mockUsers.find(user => user.userId === userId);
};

// Helper function to format activity posts for the feed
export const formatActivityPosts = () => {
  return mockActivityPosts.map(post => {
    const user = getUserById(post.userId);
    return {
      id: post.id,
      user: user?.name || "Unknown User",
      avatar: user?.profileImage || "/placeholder.svg",
      content: `${post.badgeType} ${post.habitName.toLowerCase()}${post.streakCount ? ` - ${post.streakCount} day streak!` : ''}`,
      timeAgo: post.timestamp,
      reactions: getRandomReactions(),
      comments: Math.floor(Math.random() * 8) + 1,
      caption: post.message,
      habitType: post.habitType as 'workout' | 'reading' | 'meditation' | 'nutrition' | 'sleep',
      streakCount: post.streakCount
    };
  });
};

// Helper function to get random reactions for posts
const getRandomReactions = () => {
  const allReactions = ["💪", "🔥", "👏", "✨", "🎉", "❤️", "🚀", "🙌"];
  const numReactions = Math.floor(Math.random() * 4) + 2;
  const shuffled = allReactions.sort(() => 0.5 - Math.random());
  return shuffled.slice(0, numReactions);
};

